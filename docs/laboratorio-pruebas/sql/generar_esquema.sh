#!/usr/bin/env bash
# Genera 00_esquema.sql a partir de las migraciones de Django.
# Uso (desde backend/, con el entorno virtual activo y DATABASE_URL apuntando a un PostgreSQL):
#   bash ../docs/laboratorio-pruebas/sql/generar_esquema.sh
set -eo pipefail # si cualquier comando falla, se detiene (no deja un archivo a medias)
SALIDA="../docs/laboratorio-pruebas/sql/00_esquema.sql"

{
echo "SET client_encoding = 'UTF8';"
echo "-- ====================================================================="
echo "-- 00_esquema.sql — Crea la base de datos de la PWA desde cero"
echo "-- Generado con generar_esquema.sh (python manage.py sqlmigrate)"
echo "-- Ejecutar en una base PostgreSQL VACÍA. Después: 02_carga.sql"
echo "-- ====================================================================="
echo
python manage.py showmigrations --plan | awk '{print $2}' | while IFS=. read -r app nombre; do
  echo "-- ---------- $app.$nombre ----------"
  python manage.py sqlmigrate "$app" "$nombre"
  echo
done
echo "-- Registro de migraciones: así Django sabe que el esquema ya está aplicado"
echo "-- y 'migrate' no intenta volver a crear las tablas."
echo "CREATE TABLE IF NOT EXISTS django_migrations ("
echo "    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
echo "    app varchar(255) NOT NULL,"
echo "    name varchar(255) NOT NULL,"
echo "    applied timestamp with time zone NOT NULL"
echo ");"
echo "INSERT INTO django_migrations (app, name, applied) VALUES"
python manage.py showmigrations --plan | awk '{print $2}' | sed "s/^\([^.]*\)\.\(.*\)$/    ('\1', '\2', now()),/" | sed '$ s/,$/;/'
} > "$SALIDA"

echo "Listo: $SALIDA"